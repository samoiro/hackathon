-- 추천 카드의 "도움돼요" · "해당 없어요" 피드백. 업종 × 할 일 유형별 반응을 모아 강추 점수와 프롬프트 예시에 반영한다.
-- 기준: ai-server/docs/SUGGESTION_TODOS_DRAFT.md "피드백"
-- 로그인이 없어서 분석 1건의 카드 1장에 1표만 받는다. 다시 누르면 표를 바꾼다.

create table suggestion_feedback (
    id               bigint generated by default as identity primary key,
    analysis_id      uuid    not null references briefing_analysis_job (id) on delete cascade,
    industry_id      bigint  not null references industry (id),
    card_key         text    not null check (card_key ~ '^(EVENT|INGREDIENT|SUPPLY):[A-Z_]+:([0-9]+|-)$'),
    category         text    not null check (category in ('EVENT', 'INGREDIENT', 'SUPPLY')),
    task_type        text    not null check (task_type ~ '^[A-Z_]+$'),
    item_id          bigint,
    vote             text    not null check (vote in ('HELPFUL', 'NOT_RELEVANT')),
    created_datetime timestamptz(0) not null default current_timestamp(0),
    updated_datetime timestamptz(0) not null default current_timestamp(0),
    unique (analysis_id, card_key),
    check (card_key = category || ':' || task_type || ':' || coalesce(item_id::text, '-'))
);

-- 업종 × 묶음 × 유형별 도움 비율 집계용
create index suggestion_feedback_stats_idx on suggestion_feedback (industry_id, category, task_type);

create trigger suggestion_feedback_timestamps before update on suggestion_feedback
for each row execute function batch_job_set_timestamps();

