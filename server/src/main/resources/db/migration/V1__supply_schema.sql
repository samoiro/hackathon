-- 업종·부자재 준비표 스키마. 데이터는 V2__supply_seed.sql

create table industry (
    id       bigint generated by default as identity primary key,
    category text not null check (category in ('음식점', '소매점', '단체·개인서비스업')),
    name     text not null unique
);

-- 준비 시점을 정하는 사건(날씨·행사·기념일 등)
create table supply_trigger (
    code  text primary key,
    label text not null,
    type  text not null check (type in ('WEATHER', 'EVENT', 'HOLIDAY', 'SCHOOL', 'SEASON'))
);

create table supply (
    id   bigint generated by default as identity primary key,
    name text not null unique
);

-- 노션 표 한 줄을 트리거별로 나눈 규칙 (조회 단순화를 위해 같은 줄의 품목·준비 시점이 트리거 수만큼 반복된다)
create table supply_rule (
    id            bigint generated by default as identity primary key,
    industry_id   bigint  not null references industry (id),
    trigger_code  text    not null references supply_trigger (code),
    trigger_text  text    not null, -- 노션 원문 (예: 김장철(보쌈을 함께 할 때))
    forecast      boolean not null, -- true: 날씨 예보 기준, false: 날짜 기준
    lead_days_min integer,          -- 며칠 전에 준비하는지 (D-1~3 이면 1~3). 수요가 줄면 둘 다 null
    lead_days_max integer,
    demand        text    not null check (demand in ('UP', 'STRONG_UP', 'DOWN')),
    unique (industry_id, trigger_code),
    check ((lead_days_min is null) = (lead_days_max is null)),
    check (lead_days_min between 0 and lead_days_max)
);

create index supply_rule_trigger_idx on supply_rule (trigger_code);

create table supply_rule_item (
    rule_id    bigint   not null references supply_rule (id) on delete cascade,
    supply_id  bigint   not null references supply (id),
    kind       text     not null check (kind in ('SUPPLY', 'STOCK')), -- STOCK: 부자재가 아니라 손님에게 파는 상품
    sort_order smallint not null,                                      -- 노션 표에 적힌 순서
    primary key (rule_id, supply_id)
);

create index supply_rule_item_supply_idx on supply_rule_item (supply_id);
